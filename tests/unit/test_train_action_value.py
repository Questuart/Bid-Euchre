# ── End-to-End ────────────────────────────────────────────────


class TestEndToEnd:
    def test_full_pipeline(self, smoke_parquet_path):
        """Full pipeline: load → split → train → artifact → gate."""
        df = load_dataset(smoke_parquet_path)
        train_df, val_df, test_df = split_by_deal(df, seed=42)

        models = {}
        for family in ("suit", "high", "low"):
            models[family] = train_family_model(train_df, val_df, family)
        models["pass"] = train_pass_model(train_df, val_df)

        artifact = build_artifact(
            models,
            seed=42,
            n_deals=df["deal_id"].nunique(),
            continuation_artifact="hybrid_r0_full.json",
        )

        # Should pass Gate X2
        validate_gate_x2(artifact)

        # Should be valid JSON
        json_str = json.dumps(artifact)
        reloaded = json.loads(json_str)
        assert reloaded["schema_version"] == "action_value_olsa_v1"
