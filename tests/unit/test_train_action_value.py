# ── Gate X2 ───────────────────────────────────────────────────


class TestGateX2:
    def test_passes_on_valid_artifact(self, artifact):
        """Should not raise on a real trained artifact."""
        validate_gate_x2(artifact)

    def test_fails_on_low_r2(self):
        """Should raise AssertionError when R² is below threshold."""
        bad_artifact = {
            "models": {
                "suit": {"r_squared": 0.001},
                "high": {"r_squared": 0.10},
                "low": {"r_squared": 0.10},
                "pass": {"r_squared": 0.10},
            }
        }
        with pytest.raises(AssertionError, match="suit"):
            validate_gate_x2(bad_artifact)


